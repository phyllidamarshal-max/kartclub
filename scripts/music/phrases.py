def parse_bar(notation):
    events=[]
    position=0.0
    for token in notation.split():
        pitch,duration=token.split(':')
        duration=float(duration)
        events.append((position,duration,None if pitch=='r' else int(pitch)))
        position+=duration
    if abs(position-4)>1e-8:
        raise ValueError(f'Bar has {position} beats: {notation}')
    return events


def chord_pitches(symbol):
    root=int(symbol[:-1])
    return [root,root+(4 if symbol[-1]=='M' else 3),root+7]


def close_voicing(key, symbol, previous=None):
    """Keep three distinct voices near their previous pitches, in a warm register."""
    chord=chord_pitches(symbol)
    candidates=[]
    for inversion in range(3):
        offsets=chord[inversion:]+[n+12 for n in chord[:inversion]]
        for octave in (-24,-12,0):
            notes=[key+n+octave for n in offsets]
            if notes[0]>=45 and notes[-1]<=76:
                candidates.append(notes)
    reference=previous or [key-12,key-8,key-5]
    return min(candidates,key=lambda notes:sum(abs(a-b) for a,b in zip(notes,reference)))


def melody_events(track_id, section, bar):
    chart=CHARTS[track_id]
    return parse_bar(chart['a' if section<2 else 'b'][bar%8])
